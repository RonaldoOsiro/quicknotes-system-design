const API_URL = 'https://jsonplaceholder.typicode.com/posts';

// Reusable async request function with error checking
async function request(url, options = {}) {
  try {
    const response = await fetch(url, options);
    if (!response.ok) {
      throw new Error(`HTTP error! Status: ${response.status}`);
    }
    const text = await response.text();
    return {
      data: text ? JSON.parse(text) : {},
      status: response.status
    };
  } catch (error) {
    console.error('API Request Error:', error);
    throw error;
  }
}

// DOM Elements
const loadBtn = document.getElementById('load-btn');
const submitBtn = document.getElementById('submit-btn');
const statusEl = document.getElementById('status');
const noteForm = document.getElementById('note-form');
const titleInput = document.getElementById('title-input');
const bodyInput = document.getElementById('body-input');
const notesList = document.getElementById('notes-list');

// Helper to set status message and style
function setStatus(message, type = '') {
  statusEl.textContent = message;
  statusEl.className = 'status ' + type;
}

// Render notes to the list using textContent only to prevent XSS
function renderNotes(notes) {
  notesList.innerHTML = '';
  if (!notes || notes.length === 0) {
    const li = document.createElement('li');
    li.textContent = 'No notes available.';
    li.className = 'empty-state';
    notesList.appendChild(li);
    return;
  }

  notes.forEach(note => {
    const li = document.createElement('li');
    li.className = 'note-item';
    li.dataset.id = note.id;

    const h3 = document.createElement('h3');
    h3.textContent = note.title;

    const p = document.createElement('p');
    p.textContent = note.body;

    const deleteBtn = document.createElement('button');
    deleteBtn.textContent = 'Delete';
    deleteBtn.className = 'delete-btn';
    deleteBtn.addEventListener('click', () => deleteNote(note.id, li));

    li.appendChild(h3);
    li.appendChild(p);
    li.appendChild(deleteBtn);
    notesList.appendChild(li);
  });
}

// GET Notes
async function loadNotes() {
  loadBtn.disabled = true;
  setStatus('Loading notes...', 'loading');

  try {
    const { data: notes } = await request(`${API_URL}?_limit=10`);
    renderNotes(notes);
    if (notes.length === 0) {
      setStatus('No notes found.', 'error');
    } else {
      setStatus('Loaded 10 notes from the server.', 'success');
    }
  } catch (error) {
    setStatus('Failed to load notes. Please check your network connection.', 'error');
    renderNotes([]);
  } finally {
    loadBtn.disabled = false;
  }
}

// POST Note
async function createNote(event) {
  event.preventDefault();
  const title = titleInput.value.trim();
  const body = bodyInput.value.trim();

  // Validation
  if (!title) {
    setStatus('Title is required.', 'error');
    return;
  }
  if (title.length > 100) {
    setStatus('Title must be 100 characters or less.', 'error');
    return;
  }

  submitBtn.disabled = true;
  setStatus('Creating note...', 'loading');

  try {
    const newNoteData = { title, body, userId: 1 };
    const { data: createdNote, status } = await request(API_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(newNoteData)
    });

    // Note on JSONPlaceholder: JSONPlaceholder simulates creation and always returns id 101.
    // In a real application, createdNote.id would be the unique primary key generated by the server database.

    const currentItems = Array.from(notesList.querySelectorAll('.note-item')).map(li => ({
      id: li.dataset.id,
      title: li.querySelector('h3').textContent,
      body: li.querySelector('p').textContent
    }));

    const updatedNotes = [createdNote, ...currentItems];
    renderNotes(updatedNotes);

    setStatus(`Note created (status ${status}, id ${createdNote.id}).`, 'success');
    noteForm.reset();
  } catch (error) {
    setStatus('Failed to create note. Please try again.', 'error');
  } finally {
    submitBtn.disabled = false;
  }
}

// DELETE Note
async function deleteNote(id, listItemEl) {
  const deleteBtnEl = listItemEl.querySelector('.delete-btn');
  deleteBtnEl.disabled = true;
  setStatus('Deleting note...', 'loading');

  try {
    // JSONPlaceholder returns 200/204 on successful DELETE.
    // Note: JSONPlaceholder does not actually persist deletions on the server side,
    // so we handle it client-side by removing the element immediately.
    const { status } = await request(`${API_URL}/${id}`, {
      method: 'DELETE'
    });

    listItemEl.remove();

    if (notesList.children.length === 0) {
      renderNotes([]);
    }

    setStatus(`Note successfully deleted (status ${status}).`, 'success');
  } catch (error) {
    setStatus('Failed to delete note from server.', 'error');
    deleteBtnEl.disabled = false;
  }
}

// Event Listeners
loadBtn.addEventListener('click', loadNotes);
noteForm.addEventListener('submit', createNote);